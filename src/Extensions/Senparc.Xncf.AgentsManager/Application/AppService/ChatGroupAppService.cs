        /// <summary>
        /// Searches enabled ChatGroups by name or description and returns a bounded member summary.
        /// </summary>
        /// <param name="request">The search text and result limit.</param>
        /// <returns>A task containing a formatted search response.</returns>
        [FunctionRender(typeof(AgentsManagerResource), "Function.Agents.SearchChatGroup.Name", "Function.Agents.SearchChatGroup.Description", typeof(Register))]
        public async Task<StringAppResponse> FindChatGroups(ChatGroup_FindByNameRequest request)
        {
            return await this.GetStringResponseAsync(async (response, logger) =>
            {
                var query = request.Query?.Trim();
                if (string.IsNullOrWhiteSpace(query))
                {
                    return "请输入 ChatGroup 名称或适用场景关键词。";
                }
                if (query.Length > 100)
                {
                    return "搜索词最多 100 个字符。";
                }

                var topN = request.TopN <= 0 ? 5 : Math.Min(request.TopN, 10);
                if (int.TryParse(query, out var requestedGroupId) && requestedGroupId > 0)
                {
                    var exactGroup = await _chatGroupService.GetObjectAsync(
                        group => group.Id == requestedGroupId && group.Enable);
                    return exactGroup == null
                        ? $"没有找到启用状态的 ChatGroup，ID：{requestedGroupId}。"
                        : FormatChatGroup(exactGroup, Array.Empty<ChatGroupMember>(), new Dictionary<int, string>());
                }
                var groups = await _chatGroupService.GetObjectListAsync(
                    0,
                    topN,
                    group => group.Enable
                        && (group.Name.Contains(query) || group.Description.Contains(query)),
                    group => group.Id,
                    Ncf.Core.Enums.OrderingType.Descending);
                var groupList = groups.ToList();
                if (groupList.Count == 0)
                {
                    return $"没有找到名称或说明包含“{query}”的 ChatGroup。";
                }

                var memberLinksByGroup = new Dictionary<int, List<ChatGroupMember>>();
                foreach (var group in groupList)
                {
                    var memberPage = await _chatGroupMemeberService.GetObjectListAsync(
                        0,
                        13,
                        member => member.ChatGroupId == group.Id,
                        member => member.Id,
                        Ncf.Core.Enums.OrderingType.Descending);
                    memberLinksByGroup[group.Id] = memberPage.ToList();
                }

                var memberLinks = memberLinksByGroup.Values.SelectMany(members => members).ToList();
                var agentIds = memberLinks.Select(member => member.AgentTemplateId).Distinct().ToList();
                var agents = agentIds.Count == 0
                    ? new List<AgentTemplate>()
                    : await _agentsTemplateService.GetFullListAsync(agent => agentIds.Contains(agent.Id));
                var agentNames = agents.ToDictionary(agent => agent.Id, agent => agent.Name);

                return string.Join("\n", groupList.Select(group => FormatChatGroup(
                    group,
                    memberLinksByGroup[group.Id],
                    agentNames)));
            });
        }

        private static string FormatChatGroup(
            ChatGroup group,
            IReadOnlyCollection<ChatGroupMember> groupMembers,
            IReadOnlyDictionary<int, string> agentNames)
        {
            var members = groupMembers
                .Select(member => agentNames.TryGetValue(member.AgentTemplateId, out var name)
                    ? name
                    : $"AgentTemplate #{member.AgentTemplateId}")
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
            var description = string.IsNullOrWhiteSpace(group.Description)
                ? "(无说明)"
                : group.Description.Length <= 200
                    ? group.Description
                    : group.Description.Substring(0, 200) + "…";
            var memberSummary = string.Join("、", members.Take(12));
            if (members.Count > 12)
            {
                memberSummary += " 等更多成员";
            }
            return $"ID: {group.Id}; 名称: {group.Name}; 说明: {description}; 成员: {memberSummary}";
        }

        /// <summary>
        /// Creates or updates a ChatGroup, resolves local member identifiers/names,
        /// and persists the resulting membership.
        /// </summary>
        /// <param name="request">The ChatGroup name, description, target group, and member inputs.</param>
        /// <returns>A task containing operation logs.</returns>
        /// <exception cref="NcfExceptionBase">Thrown when members or group configuration are invalid.</exception>
        [FunctionRender(typeof(AgentsManagerResource), "Function.Agents.ManageChatGroup.Name", "Function.Agents.ManageChatGroup.Description", typeof(Register))]
        public async Task<StringAppResponse> ManageChatGroupManage(ChatGroup_ManageChatGroupRequest request)
        {
            return await this.GetStringResponseAsync(async (response, logger) =>
            {
                var enabledAgents = await _agentsTemplateService.GetFullListAsync(z => z.Enable, z => z.Id, Ncf.Core.Enums.OrderingType.Descending);

                //Legacy comment translated to English.
                var preferredHost = await EnsurePreferredHostAgentAsync(enabledAgents, logger);
                var adminId = preferredHost.Id;
                var enterAgentId = preferredHost.Id;

                //Legacy comment translated to English.
                ChatGroup chatGroup = null;
                var chatGroupDto = new ChatGroupDto(request.Name, true, ChatGroupState.Unstart, request.Description, adminId, enterAgentId);
                var isNew = false;
                if (string.Equals(request.ChatGroup, "New", StringComparison.OrdinalIgnoreCase))
                {
                    var scenario = request.Description?.Trim();
                    if (string.IsNullOrWhiteSpace(scenario))
                    {
                        return "新建 ChatGroup 时必须提供适用场景说明。";
                    }

                    chatGroupDto.Description = $"{AdminChatAutoGeneratedMarker}\n适用场景：{scenario}";
                    chatGroup = new ChatGroup(chatGroupDto);
                    isNew = true;
                }
                else
                {
                    int.TryParse(request.ChatGroup, out int chatGroupId);
                    chatGroup = await _chatGroupService.GetObjectAsync(z => z.Id == chatGroupId);
                    if (chatGroup == null)
                    {
                        return $"未找到需要编辑的 ChatGroup，ID：{chatGroupId}";
                    }

                    //Legacy comment translated to English.
                    chatGroupDto.Enable = chatGroup.Enable;
                    chatGroup.Update(chatGroupDto);
                }

                //Legacy comment translated to English.
                var memberList = new List<ChatGroupMember>();
                var rawMemberInputs = new List<string>();
                rawMemberInputs.AddRange((request.Members ?? Array.Empty<string>()).Where(z => !string.IsNullOrWhiteSpace(z)));
                rawMemberInputs.AddRange(SplitInputs(request.MemberNamesOrIds));

                var memberIdList = new List<int>();
                foreach (var memberInput in rawMemberInputs.Distinct(StringComparer.OrdinalIgnoreCase))
                {
                    var memberResult = ResolveAgentId(enabledAgents, memberInput);
                    if (!memberResult.Success)
                    {
                        return $"群成员选择失败：{memberResult.ErrorMessage}";
                    }

                    if (!memberIdList.Contains(memberResult.AgentId))
                    {
                        memberIdList.Add(memberResult.AgentId);
                    }
                }

                if (memberIdList.Count == 0)
                {
                    return "请至少提供一个群成员（支持 ID 或名称）";
                }

                //Legacy comment translated to English.
                if (!memberIdList.Contains(chatGroupDto.EnterAgentTemplateId))
                {
                    memberIdList.Add(chatGroupDto.EnterAgentTemplateId);
                }

                await _chatGroupService.SaveObjectAsync(chatGroup);
                logger.Append($"ChatGroup {(isNew ? "新增" : "编辑")} 成功！");

                foreach (var agentId in memberIdList)
                {
                    var chatGroupMemberDto = new ChatGroupMemberDto(null, chatGroup.Id, agentId);
                    var member = new ChatGroupMember(chatGroupMemberDto);
                    member.ResetUID();
                    memberList.Add(member);
                }
                await _chatGroupMemeberService.SaveObjectListAsync(memberList);

                logger.Append($"ChatGroup 成员添加成功！");

                return logger.ToString();
            });
        }

        /// <summary>
        /// Selects the highest-scoring enabled host agent or creates the system's default
        /// intelligent host when none exists.
        /// </summary>
        /// <param name="enabledAgents">Enabled agent templates available for selection.</param>
        /// <param name="logger">The application-service logger.</param>
        /// <returns>A task containing the selected or newly created host agent.</returns>
        private async Task<AgentTemplate> EnsurePreferredHostAgentAsync(List<AgentTemplate> enabledAgents, AppServiceLogger logger)
        {
            var hostCandidates = enabledAgents
                .Where(z => !string.IsNullOrWhiteSpace(z.Name)
                            && z.Name.Contains("主持人", StringComparison.OrdinalIgnoreCase))
                .ToList();

            if (hostCandidates.Count > 0)
            {
                var scored = new List<(AgentTemplate Agent, float Score)>();
                foreach (var candidate in hostCandidates)
                {
                    var score = await GetAgentScoreByPromptCodeAsync(candidate.PromptCode);
                    scored.Add((candidate, score));
                }

                var selected = scored
                    .OrderByDescending(z => z.Score)
                    .ThenByDescending(z => z.Agent.Id)
                    .First().Agent;

                logger.Append($"已自动选择主持人 Agent：{selected.Name}(ID:{selected.Id})");
                return selected;
            }

            var promptRange = await _promptRangeService.AddAsync("智能主持人");

            var chatModel = await _aIModelService.GetObjectAsync(
                z => z.Show && z.ConfigModelType == Senparc.Xncf.AIKernel.Domain.Models.ConfigModelType.Chat)
                ?? await _aIModelService.GetObjectAsync(
                    z => z.ConfigModelType == Senparc.Xncf.AIKernel.Domain.Models.ConfigModelType.Chat);

            if (chatModel == null)
            {
                throw new NcfExceptionBase("未找到可用的 Chat 类型 AI 模型，无法自动创建主持人 Agent");
            }

            var promptItem = await _promptItemService.AddPromptItemAsync(new PromptItem_AddRequest
            {
                RangeId = promptRange.Id,
                ModelId = chatModel.Id,
                Content = "你是一个多智能体小组的主持人（群主）。职责：维护讨论秩序、拆解任务、分配发言顺序、在信息不足时追问澄清、在出现分歧时推动收敛，并输出清晰的阶段结论。你应保持中立、简洁、可执行，不直接替代成员完成专业内容。",
                IsTopTactic = true,
                IsNewTactic = false,
                IsNewSubTactic = false,
                IsNewAiming = false,
                NumsOfResults = 0,
                MaxToken = 3000,
                Temperature = 0.4f,
                TopP = 0.8f,
                FrequencyPenalty = 0,
                PresencePenalty = 0,
                StopSequences = null,
                IsDraft = true,
                Note = "自动主持人",
                ExpectedResultsJson = string.Empty,
                Prefix = string.Empty,
                Suffix = string.Empty,
                VariableDictJson = string.Empty
            });

            var hostAgent = new AgentTemplate(
                name: "智能主持人",
                systemMessage: promptItem.FullVersion,
                enable: true,
                description: "系统自动创建的主持人 Agent（用于群主与对接人）",
                promptCode: promptItem.FullVersion,
                hookRobotType: HookRobotType.None,
                hookRobotParameter: string.Empty,
                avastar: null,
                functionCallNames: null,
                mcpEndpoints: null);

            await _agentsTemplateService.SaveObjectAsync(hostAgent);

            logger.Append($"未找到主持人 Agent，已自动创建：{hostAgent.Name}(ID:{hostAgent.Id})，PromptCode：{hostAgent.PromptCode}");
            return hostAgent;
        }

        /// <summary>
        /// Resolves a PromptRange prompt code and returns its average evaluation score.
        /// Invalid or non-PromptRange codes return the sentinel score.
        /// </summary>
        /// <param name="promptCode">The agent prompt code.</param>
        /// <returns>A task containing the average score, or <c>-1</c> when unavailable.</returns>
        private async Task<float> GetAgentScoreByPromptCodeAsync(string promptCode)
        {
            if (string.IsNullOrWhiteSpace(promptCode))
            {
                return -1;
            }

            if (!AgentTemplateRunner.IsPromptRangeReference(promptCode))
            {
                return -1;
            }

            try
            {
                var promptItem = await _promptItemService.GetBestPromptAsync(promptCode, true);
                return promptItem == null ? -1 : (float)promptItem.EvalAvgScore;
            }
            catch
            {
                return -1;
            }
        }

        private static readonly Dictionary<string, string> AgentNameAliasMap =
            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            {
                ["提示词优化器"] = "PromptCatalyzer",
                ["优化器"] = "PromptCatalyzer"
            };

        /// <summary>
        /// Splits comma, semicolon, pipe, and newline-delimited member input into normalized tokens.
        /// </summary>
        /// <param name="rawInput">The raw member input string.</param>
        /// <returns>Non-empty trimmed tokens.</returns>
        private static List<string> SplitInputs(string rawInput)
        {
            if (string.IsNullOrWhiteSpace(rawInput))
            {
                return new List<string>();
            }

            return rawInput
                .Split(new[] { ',', '，', ';', '；', '\n', '\r', '|' }, StringSplitOptions.RemoveEmptyEntries)
                .Select(z => z.Trim())
                .Where(z => !string.IsNullOrWhiteSpace(z))
                .ToList();
        }

        /// <summary>
        /// Resolves a member token by numeric ID, alias, name, or PromptCode.
        /// </summary>
        /// <param name="enabledAgents">Enabled agent templates available for lookup.</param>
        /// <param name="rawInput">The member token.</param>
        /// <returns>Resolution status, agent ID, and an error message when resolution fails.</returns>
        private (bool Success, int AgentId, string ErrorMessage) ResolveAgentId(List<AgentTemplate> enabledAgents, string rawInput)
        {
            if (string.IsNullOrWhiteSpace(rawInput))
            {
                return (false, 0, "输入为空，请传入 Agent ID、名称或 PromptCode");
            }

            var input = rawInput.Trim();

            if (int.TryParse(input, out var agentId))
            {
                var byId = enabledAgents.FirstOrDefault(z => z.Id == agentId);
                if (byId == null)
                {
                    return (false, 0, $"未找到启用状态的 Agent，ID：{agentId}");
                }
                return (true, byId.Id, string.Empty);
            }

            if (AgentNameAliasMap.TryGetValue(input, out var aliasName))
            {
                input = aliasName;
            }

            var exactName = enabledAgents.Where(z => string.Equals(z.Name, input, StringComparison.OrdinalIgnoreCase)).ToList();
            if (exactName.Count == 1)
            {
                return (true, exactName[0].Id, string.Empty);
            }

            var exactPromptCode = enabledAgents.Where(z => string.Equals(z.PromptCode, input, StringComparison.OrdinalIgnoreCase)).ToList();
            if (exactPromptCode.Count == 1)
            {
                return (true, exactPromptCode[0].Id, string.Empty);
            }

            var fuzzy = enabledAgents.Where(z =>
                    (!string.IsNullOrWhiteSpace(z.Name) && z.Name.Contains(input, StringComparison.OrdinalIgnoreCase))
                    || (!string.IsNullOrWhiteSpace(z.PromptCode) && z.PromptCode.Contains(input, StringComparison.OrdinalIgnoreCase)))
                .OrderByDescending(z => z.Id)
                .ToList();

            if (fuzzy.Count == 1)
            {
                return (true, fuzzy[0].Id, string.Empty);
            }

            if (fuzzy.Count > 1)
            {
                var options = string.Join("；", fuzzy.Take(5).Select(z => $"{z.Id}:{z.Name}({z.PromptCode})"));
                return (false, 0, $"输入“{rawInput}”匹配到多个 Agent，请指定 ID：{options}");
            }

            return (false, 0, $"未找到匹配的 Agent：{rawInput}");
        }

        /// <summary>
        /// Starts one or more ChatGroups from a FunctionRender request and returns serialized task results.
        /// </summary>
        /// <param name="request">The selected groups, command, model, and human-approval options.</param>
        /// <returns>A task containing operation logs and started-task metadata.</returns>
        [FunctionRender(typeof(AgentsManagerResource), "Function.Agents.StartChatGroup.Name", "Function.Agents.StartChatGroup.Description", typeof(Register))]
        public Task<StringAppResponse> StartChatToolTask(ChatGroup_ChatToolRunRequest request)
        {
            return this.GetStringResponseAsync(async (response, logger) =>
            {
                if (request == null || request.ChatGroupId <= 0)
                {
                    response.Success = false;
                    response.ErrorMessage = "ChatGroupId must be greater than 0.";
                    return null;
                }
                if (string.IsNullOrWhiteSpace(request.Command))
                {
                    response.Success = false;
                    response.ErrorMessage = "Command is required.";
                    return null;
                }

                var group = await _chatGroupService.GetObjectAsync(item =>
                    item.Id == request.ChatGroupId && item.Enable);
                if (group == null)
                {
                    response.Success = false;
                    response.ErrorMessage = $"Enabled ChatGroup was not found: {request.ChatGroupId}.";
                    return null;
                }

                var started = await _chatGroupService.StartChatGroupInThreadAsync(new ChatGroupRunCommand
                {
                    Name = $"AdminChat-{request.ChatGroupId}-{DateTime.Now:yyyyMMddHHmmss}",
                    ChatGroupId = request.ChatGroupId,
                    AiModelId = 0,
                    PromptCommand = request.Command.Trim(),
                    Description = "Started by AdminChat slash command",
                    Personality = true,
                    RequireHumanApproval = false,
                    HumanInTheLoopLevel = HumanInTheLoopLevel.Automatic,
                    PluginToolPermission = ToolPermissionMode.Inherit,
                    McpToolPermission = ToolPermissionMode.Inherit,
                    IncludeHumanParticipant = false,
                    HumanRecipientUserId = GetCurrentAdminUserId(),
                    HookPlatform = HookPlatform.None,
                    HookParameter = string.Empty,
                    ChatMaxRound = ChatGroupService.DefaultChatMaxRound
                });

                logger.Append(JsonSerializer.Serialize(new
                {
                    kind = "admin-chat-action",
                    actions = new[]
                    {
                        new
                        {
                            type = "agents-task",
                            task = new
                            {
                                started.ChatTaskId,
                                started.ChatGroupId,
                                started.ChatGroupName,
                                Status = started.Status.ToString()
                            }
                        }
                    }
                }));
                return logger.GetLogs();
            });
        }

        [FunctionRender(typeof(AgentsManagerResource), "Function.Agents.StartChatGroup.Name", "Function.Agents.StartChatGroup.Description", typeof(Register))]
        public async Task<StringAppResponse> RunChatGroup(ChatGroup_RunChatGroupRequest request)
        {
            return await this.GetStringResponseAsync(async (response, logger) =>
            {
                //Legacy comment translated to English.
                if ((request.ChatGroups?.Length ?? 0) == 0)
                {
                    return "至少选择一个组！";
                }

                var aiModelSelected = request.AIModel;
                var aiModelId = 0;

                if (!string.IsNullOrWhiteSpace(aiModelSelected)
                    && !string.Equals(aiModelSelected, "Default", StringComparison.OrdinalIgnoreCase)
                    && int.TryParse(aiModelSelected, out var selectedModelId)
                    && selectedModelId > 0)
                {
                    aiModelId = selectedModelId;
                }

                var tasks = new List<ChatGroupRunResult>();
                foreach (var chatGroupId in request.ChatGroups.Select(z => int.Parse(z)))
                {
                    var runRequest = new ChatGroupRunCommand
                    {
                        Name = $"ChatGroup-{chatGroupId}-{DateTime.Now:yyyyMMddHHmmss}",
                        ChatGroupId = chatGroupId,
                        AiModelId = aiModelId,
                        PromptCommand = request.Command,
                        Description = "由 FunctionRender 启动",
                        Personality = request.Individuation,
                        RequireHumanApproval = request.RequireHumanApproval,
                        HumanInTheLoopLevel = request.HumanInTheLoopLevel,
                        PluginToolPermission = request.PluginToolPermission,
                        McpToolPermission = request.McpToolPermission,
                        IncludeHumanParticipant = request.IncludeHumanParticipant,
                        HumanRecipientUserId = GetCurrentAdminUserId(),
                        HookPlatform = HookPlatform.None,
                        HookParameter = string.Empty,
                        ChatMaxRound = ChatGroupService.DefaultChatMaxRound
                    };

                    var started = await _chatGroupService.StartChatGroupInThreadAsync(runRequest);
                    tasks.Add(started);
                }

                logger.Append(JsonSerializer.Serialize(new
                {
                    kind = "admin-chat-action",
                    actions = tasks.Select(task => new
