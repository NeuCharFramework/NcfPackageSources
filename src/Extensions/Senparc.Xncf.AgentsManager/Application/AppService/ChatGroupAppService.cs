        /// <summary>
        /// Adds or removes one local/remote participant from an existing Studio team.
        /// </summary>
        /// <param name="groupId">The ChatGroup identifier.</param>
        /// <param name="participantKey">The local or remote participant key.</param>
        /// <param name="remove">Whether the participant should be removed.</param>
        /// <returns>A task containing the operation result.</returns>
        /// <exception cref="NcfExceptionBase">Thrown when the participant is invalid or a required role would be removed.</exception>
        [ApiBind(ApiRequestMethod = ApiRequestMethod.Post)]
        public async Task<AppResponseBase<ChatGroupDto>> CreateStudioTeam([FromBody] StudioTeamRequest request)
        {
            return await this.GetResponseAsync<ChatGroupDto>(async (response, logger) =>
            {
                if (request == null || string.IsNullOrWhiteSpace(request.Name) || request.Name.Trim().Length > 150)
                {
                    throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.InvalidTeamName"));
                }

                var keys = (request.ParticipantKeys ?? new List<string>()).Distinct().ToList();
                if (keys.Count == 0)
                {
                    throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.SelectMembers"));
                }

                var participants = new List<(bool Remote, int Id)>();
                foreach (var key in keys)
                {
                    var participant = ParseStudioParticipant(key);
                    await ValidateStudioParticipantAsync(participant.Remote, participant.Id);
                    participants.Add(participant);
                }

                var localIds = participants.Where(item => !item.Remote).Select(item => item.Id).ToList();
                if (!localIds.Contains(request.AdminAgentTemplateId) || !localIds.Contains(request.EnterAgentTemplateId))
                {
                    throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.LocalRolesRequired"));
                }

                var admin = await _agentsTemplateService.GetObjectAsync(item => item.Id == request.AdminAgentTemplateId);
                var entry = await _agentsTemplateService.GetObjectAsync(item => item.Id == request.EnterAgentTemplateId);
                if (admin.IsHuman || entry.IsHuman)
                {
                    throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.LocalRolesRequired"));
                }

                var group = new ChatGroup(new ChatGroupDto(request.Name.Trim(), true, ChatGroupState.Unstart,
                    request.Description, admin.Id, entry.Id));
                await _chatGroupService.BeginTransactionAsync(async () =>
                {
                    await _chatGroupService.SaveObjectAsync(group);
                    foreach (var participant in participants)
                    {
                        await AddStudioMemberAsync(group.Id, participant.Remote, participant.Id);
                    }
                });
                logger.Append($"Studio team created: {group.Id}");
                return _chatGroupService.Mapping<ChatGroupDto>(group);
            });
        }

        /// <summary>
        /// Adds or removes a local or remote Studio participant from a group.
        /// </summary>
        /// <param name="groupId">The ChatGroup identifier.</param>
        /// <param name="participantKey">The participant key.</param>
        /// <param name="remove">Whether to remove the participant.</param>
        /// <returns>A task containing the operation result.</returns>
        [ApiBind(ApiRequestMethod = ApiRequestMethod.Post)]
        public async Task<AppResponseBase<string>> SetStudioParticipant(
            int groupId, string participantKey, bool remove = false)
        {
            return await this.GetResponseAsync<string>(async (response, logger) =>
            {
                var participant = ParseStudioParticipant(participantKey);
                var cache = GetRequiredService<IBaseObjectCacheStrategy>();
                using (await cache.BeginCacheLockAsync("AgentsManager.Studio.Membership", groupId.ToString()))
                {
                    var group = await _chatGroupService.GetObjectAsync(item => item.Id == groupId);
                    if (group == null)
                    {
                        throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.GroupNotFound"));
                    }
                    if (remove && !participant.Remote
                        && (participant.Id == group.AdminAgentTemplateId || participant.Id == group.EnterAgentTemplateId))
                    {
                        throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.RoleCannotRemove"));
                    }
                    if (!remove)
                    {
                        await ValidateStudioParticipantAsync(participant.Remote, participant.Id);
                    }

                    await _chatGroupService.BeginTransactionAsync(async () =>
                    {
                        if (!remove)
                        {
                            await AddStudioMemberAsync(groupId, participant.Remote, participant.Id);
                        }
                        else if (participant.Remote)
                        {
                            var members = await _chatGroupRemoteMemberService.GetFullListAsync(
                                item => item.ChatGroupId == groupId && item.RemoteAgentId == participant.Id);
                            foreach (var member in members)
                            {
                                await _chatGroupRemoteMemberService.DeleteObjectAsync(member);
                            }
                        }
                        else
                        {
                            var members = await _chatGroupMemeberService.GetFullListAsync(
                                item => item.ChatGroupId == groupId && item.AgentTemplateId == participant.Id);
                            foreach (var member in members)
                            {
                                await _chatGroupMemeberService.DeleteObjectAsync(member);
                            }
                        }
                    });
                }
                logger.Append($"Studio membership: group={groupId}, participant={participantKey}, remove={remove}");
                return AgentsManagerResource.Get(remove ? "Studio.MemberRemoved" : "Studio.MemberAdded");
            });
        }

        /// <summary>
        /// Parses a Studio participant key into its remote/local flag and numeric identifier.
        /// </summary>
        /// <param name="key">A participant key such as a local or remote prefix plus ID.</param>
        /// <returns>The parsed participant classification and ID.</returns>
        private static (bool Remote, int Id) ParseStudioParticipant(string key)
        {
            var parts = key?.Split(':');
            if (parts?.Length != 2 || (parts[0] != "local" && parts[0] != "remote")
                || !int.TryParse(parts[1], out var id) || id <= 0)
            {
                throw new NcfExceptionBase(AgentsManagerResource.Get("Studio.InvalidParticipant"));
            }
            return (parts[0] == "remote", id);
        }

