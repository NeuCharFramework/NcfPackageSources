        /// <summary>
        /// Returns an Agent collaboration graph filtered by optional agent name.
        /// </summary>
        /// <param name="filter">Optional local/remote agent name filter.</param>
        /// <returns>A response containing agents, groups, links, collaborations, and tasks.</returns>
        [ApiBind(ApiRequestMethod = ApiRequestMethod.Get)]
        public async Task<AppResponseBase<AgentGraphSnapshotResponse>> GetAgentGraphSnapshot(string filter = "")
        {
            return await this.GetResponseAsync<AgentGraphSnapshotResponse>(async (response, logger) =>
            {
                var agentExpression = new SenparcExpressionHelper<AgentTemplate>();
                agentExpression.ValueCompare.AndAlso(!string.IsNullOrWhiteSpace(filter), z => z.Name.Contains(filter));
                var agents = await _agentsTemplateService.GetObjectListAsync(0, 0, agentExpression.BuildWhereExpression(), z => z.Id, Ncf.Core.Enums.OrderingType.Descending);

                var remoteAgentExpression = new SenparcExpressionHelper<RemoteAgent>();
                remoteAgentExpression.ValueCompare.AndAlso(!string.IsNullOrWhiteSpace(filter), z => z.Name.Contains(filter));
                var remoteAgents = await _remoteAgentService.GetObjectListAsync(0, 0, remoteAgentExpression.BuildWhereExpression(), z => z.Id, Ncf.Core.Enums.OrderingType.Descending);

                var result = new AgentGraphSnapshotResponse();
                var agentIds = agents.Select(z => z.Id).Distinct().ToList();
                var remoteAgentIds = remoteAgents.Select(z => z.Id).Distinct().ToList();
                var members = await _chatGroupMemeberService.GetFullListAsync(z => agentIds.Contains(z.AgentTemplateId));
                var remoteMembers = await _chatGroupRemoteMemberService.GetFullListAsync(z => remoteAgentIds.Contains(z.RemoteAgentId));

                // Include groups even when member rows are missing but admin/enter agent is configured.
                var groupsByRole = await _chatGroupService.GetFullListAsync(
                    z => agentIds.Contains(z.AdminAgentTemplateId) || agentIds.Contains(z.EnterAgentTemplateId),
                    z => z.Id,
                    Ncf.Core.Enums.OrderingType.Ascending);

                var groupIds = members
                    .Select(z => z.ChatGroupId)
                    .Concat(remoteMembers.Select(z => z.ChatGroupId))
                    .Concat(groupsByRole.Select(z => z.Id))
                    .Distinct()
                    .ToList();

                var groups = await _chatGroupService.GetFullListAsync(
                    z => string.IsNullOrWhiteSpace(filter) || groupIds.Contains(z.Id),
                    z => z.Id, Ncf.Core.Enums.OrderingType.Ascending);
                groupIds = groups.Select(group => group.Id).ToList();

                var tasks = groupIds.Count > 0
                    ? await _chatTaskService.GetFullListAsync(z => groupIds.Contains(z.ChatGroupId) && !z.IsArchived, z => z.Id, Ncf.Core.Enums.OrderingType.Descending)
                    : new List<ChatTask>();

                var activeTasks = tasks.Where(z => !z.IsArchived && (
                    z.Status == ChatTask_Status.Waiting
                    || z.Status == ChatTask_Status.Chatting
                    || z.Status == ChatTask_Status.Paused)).ToList();

                var activeTaskCountByGroup = activeTasks
                    .GroupBy(z => z.ChatGroupId)
                    .ToDictionary(g => g.Key, g => g.Count());

                var promptScoreCache = new Dictionary<string, float>(StringComparer.OrdinalIgnoreCase);
                var publishedA2AByAgentId = agentIds.Count == 0
                    ? new Dictionary<int, PublishedA2AAgent>()
                    : (await _publishedA2AAgentService.GetFullListAsync(
                            item => agentIds.Contains(item.AgentTemplateId)))
                        .GroupBy(item => item.AgentTemplateId)
                        .ToDictionary(group => group.Key, group => group.OrderByDescending(item => item.Id).First());
                var humanInTheLoopPendingCountByTaskId = tasks
                    .Where(task => task.Status == ChatTask_Status.Paused)
                    .ToDictionary(
                        task => task.Id,
                        task => _humanInTheLoopRequestStore.GetPending(task.Id).Count);

                foreach (var agent in agents)
                {
                    var memberGroupIds = members
                        .Where(z => z.AgentTemplateId == agent.Id)
                        .Select(z => z.ChatGroupId)
                        .Concat(groups
                            .Where(group => group.AdminAgentTemplateId == agent.Id
                                || group.EnterAgentTemplateId == agent.Id)
                            .Select(group => group.Id))
                        .Distinct()
                        .ToList();
                    var chattingCount = memberGroupIds.Sum(groupId =>
                        activeTaskCountByGroup.TryGetValue(groupId, out var count) ? count : 0);
                    var agentTasks = tasks
                        .Where(task => memberGroupIds.Contains(task.ChatGroupId))
                        .ToList();
                    var pausedCount = agentTasks.Count(task => task.Status == ChatTask_Status.Paused);
                    var humanInTheLoopPausedCount = agentTasks
                        .Where(task => task.Status == ChatTask_Status.Paused)
                        .Sum(task => humanInTheLoopPendingCountByTaskId.TryGetValue(task.Id, out var count) ? count : 0);
                    var hasPublishedA2A = publishedA2AByAgentId.TryGetValue(agent.Id, out var publishedA2A);

                    var score = await GetPromptScoreAsync(agent.PromptCode, promptScoreCache);

                    result.Agents.Add(new AgentGraphAgentDto
                    {
                        Id = agent.Id,
                        ParticipantKey = $"local:{agent.Id}",
                        AgentKind = "Local",
                        Name = agent.Name,
                        Description = agent.Description,
                        IsHuman = agent.IsHuman,
                        PromptCode = agent.PromptCode,
                        Score = score,
                        ChattingCount = chattingCount,
                        PausedCount = pausedCount,
                        HumanInTheLoopPausedCount = humanInTheLoopPausedCount,
                        Enable = agent.Enable,
                        Avastar = agent.Avastar,
                        SkillKinds = AgentGraphSkillHelper.GetAgentSkillKinds(agent, hasPublishedA2A),
                        HasPublishedA2A = hasPublishedA2A,
                        PublishedA2AEnabled = publishedA2A?.Enable == true
                    });
                }

                foreach (var remoteAgent in remoteAgents)
                {
                    var memberGroupIds = remoteMembers.Where(z => z.RemoteAgentId == remoteAgent.Id).Select(z => z.ChatGroupId).Distinct().ToList();
                    var chattingCount = memberGroupIds.Sum(groupId =>
                        activeTaskCountByGroup.TryGetValue(groupId, out var count) ? count : 0);
                    var agentTasks = tasks
                        .Where(task => memberGroupIds.Contains(task.ChatGroupId))
                        .ToList();

                    result.Agents.Add(new AgentGraphAgentDto
                    {
                        Id = remoteAgent.Id,
                        ParticipantKey = RemoteA2AAgentFactory.BuildParticipantKey(remoteAgent.Id),
                        AgentKind = "RemoteA2A",
                        Name = remoteAgent.Name,
                        Description = remoteAgent.Description,
                        PromptCode = "A2A",
                        Score = -1,
                        ChattingCount = chattingCount,
                        PausedCount = agentTasks.Count(task => task.Status == ChatTask_Status.Paused),
                        HumanInTheLoopPausedCount = agentTasks
                            .Where(task => task.Status == ChatTask_Status.Paused)
                            .Sum(task => humanInTheLoopPendingCountByTaskId.TryGetValue(task.Id, out var count) ? count : 0),
                        Enable = remoteAgent.Enable,
                        Avastar = null,
                        ConnectionStatus = (int)remoteAgent.ConnectionStatus,
                        SkillKinds = new List<string> { "a2a" }
                    });
                }

                foreach (var group in groups)
                {
                    var statusMap = tasks
                        .Where(z => z.ChatGroupId == group.Id)
                        .GroupBy(z => (int)z.Status)
                        .ToDictionary(g => g.Key, g => g.Count());
                    var groupTasks = tasks.Where(task => task.ChatGroupId == group.Id).ToList();
                    var pausedTaskCount = groupTasks.Count(task => task.Status == ChatTask_Status.Paused);
                    var humanInTheLoopPendingCount = groupTasks
                        .Where(task => task.Status == ChatTask_Status.Paused)
                        .Sum(task => humanInTheLoopPendingCountByTaskId.TryGetValue(task.Id, out var count) ? count : 0);

                    var memberAgentIds = members
                        .Where(z => z.ChatGroupId == group.Id)
                        .Select(z => z.AgentTemplateId)
                        .Distinct()
                        .ToList();

                    if (!memberAgentIds.Contains(group.AdminAgentTemplateId) && agentIds.Contains(group.AdminAgentTemplateId))
                    {
                        memberAgentIds.Add(group.AdminAgentTemplateId);
                    }

                    if (!memberAgentIds.Contains(group.EnterAgentTemplateId) && agentIds.Contains(group.EnterAgentTemplateId))
                    {
                        memberAgentIds.Add(group.EnterAgentTemplateId);
                    }

                    var memberParticipantKeys = memberAgentIds
                        .Select(z => $"local:{z}")
                        .Concat(remoteMembers
                            .Where(z => z.ChatGroupId == group.Id)
                            .Select(z => RemoteA2AAgentFactory.BuildParticipantKey(z.RemoteAgentId)))
                        .Distinct()
                        .ToList();

                    result.Groups.Add(new AgentGraphGroupDto
                    {
                        Id = group.Id,
                        Name = group.Name,
                        Enable = group.Enable,
                        State = (int)group.State,
                        AdminAgentTemplateId = group.AdminAgentTemplateId,
                        EnterAgentTemplateId = group.EnterAgentTemplateId,
                        RunningTaskCount = activeTaskCountByGroup.TryGetValue(group.Id, out var runningCount) ? runningCount : 0,
                        PausedTaskCount = pausedTaskCount,
                        HumanInTheLoopPendingCount = humanInTheLoopPendingCount,
                        TaskStatusCounts = statusMap,
                        MemberAgentIds = memberAgentIds,
                        MemberParticipantKeys = memberParticipantKeys
                    });

                    foreach (var memberAgentId in memberAgentIds)
                    {
                        result.Links.Add(new AgentGraphLinkDto
                        {
                            GroupId = group.Id,
                            AgentId = memberAgentId,
                            ParticipantKey = $"local:{memberAgentId}"
                        });
                    }

                    foreach (var remoteMember in remoteMembers.Where(z => z.ChatGroupId == group.Id))
                    {
                        result.Links.Add(new AgentGraphLinkDto
                        {
                            GroupId = group.Id,
                            ParticipantKey = RemoteA2AAgentFactory.BuildParticipantKey(remoteMember.RemoteAgentId)
                        });
                    }
                }

                foreach (var task in activeTasks)
                {
                    var memberAgentIds = members
                        .Where(z => z.ChatGroupId == task.ChatGroupId)
                        .Select(z => z.AgentTemplateId)
                        .Distinct()
                        .ToList();

                    var participantKeys = memberAgentIds
                        .Select(z => $"local:{z}")
                        .Concat(remoteMembers
                            .Where(z => z.ChatGroupId == task.ChatGroupId)
                            .Select(z => RemoteA2AAgentFactory.BuildParticipantKey(z.RemoteAgentId)))
                        .Distinct()
                        .ToList();

                    participantKeys = result.Links.Where(link => link.GroupId == task.ChatGroupId)
                        .Select(link => link.ParticipantKey).Distinct().ToList();

                    result.Collaborations.Add(new AgentGraphCollaborationDto
                    {
                        TaskId = task.Id,
                        GroupId = task.ChatGroupId,
                        TaskName = task.Name,
                        Status = (int)task.Status,
                        AgentIds = memberAgentIds,
                        ParticipantKeys = participantKeys
                    });
                }

                result.Tasks = tasks.Where(task => !task.IsArchived).Select(task => new AgentGraphTaskDto
                {
                    Id = task.Id,
                    GroupId = task.ChatGroupId,
                    Name = task.Name,
                    Status = (int)task.Status,
                    StartTime = task.StartTime,
                    HumanPendingCount = humanInTheLoopPendingCountByTaskId.TryGetValue(task.Id, out var count) ? count : 0
                }).ToList();
                return result;
            });
        }

