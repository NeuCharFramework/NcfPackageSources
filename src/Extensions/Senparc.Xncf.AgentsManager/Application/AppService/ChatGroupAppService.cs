        /// <summary>
        /// Resolves and caches the average score of a PromptRange prompt reference.
        /// </summary>
        /// <param name="promptCode">The prompt reference code.</param>
        /// <param name="scoreCache">The per-request score cache.</param>
        /// <returns>A task containing the score, or <c>-1</c> when unavailable.</returns>
        private async Task<float> GetPromptScoreAsync(string promptCode, Dictionary<string, float> scoreCache)
        {
            if (string.IsNullOrWhiteSpace(promptCode))
            {
                return -1;
            }

            if (!AgentTemplateRunner.IsPromptRangeReference(promptCode))
            {
                scoreCache[promptCode] = -1;
                return -1;
            }

            if (scoreCache.TryGetValue(promptCode, out var cachedScore))
            {
                return cachedScore;
            }

            try
            {
                var promptItem = await _promptItemService.GetBestPromptAsync(promptCode, true);
                var score = promptItem == null ? -1 : (float)promptItem.EvalAvgScore;
                scoreCache[promptCode] = score;
                return score;
            }
            catch
            {
                scoreCache[promptCode] = -1;
                return -1;
            }
        }

