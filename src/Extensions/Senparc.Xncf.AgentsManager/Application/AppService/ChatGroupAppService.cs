    internal static class AgentGraphSkillHelper
    {
        /// <summary>
        /// Derives the distinct skill categories exposed by an agent template,
        /// including MCP and published A2A capabilities.
        /// </summary>
        /// <param name="agent">The agent template.</param>
        /// <param name="hasPublishedA2A">Whether the agent has a published A2A endpoint.</param>
        /// <returns>The skill category keys.</returns>
        public static List<string> GetAgentSkillKinds(AgentTemplate agent, bool hasPublishedA2A)
        {
            var kinds = AgentFunctionBindingCodec
                .Parse(agent.FunctionCallNames)
                .Select(binding => binding.Kind?.Trim().ToLowerInvariant())
                .Where(kind => kind is "function" or "workflow" or "plugin")
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();

            if (!string.IsNullOrWhiteSpace(agent.McpEndpoints))
            {
                kinds.Add("mcp");
            }

            if (hasPublishedA2A)
            {
                kinds.Add("a2a");
            }

            if (agent.IsHuman)
            {
                kinds.Add("human");
            }

            return kinds
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
        }
    }
